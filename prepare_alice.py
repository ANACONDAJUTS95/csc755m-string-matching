"""Download and clean "Alice's Adventures in Wonderland" (Project Gutenberg #11).

Steps
1. Download the plain-text UTF-8 file to data/alice_raw.txt (skipped if the
   file is already there, e.g. because you placed it by hand).
2. Keep only the text between the "*** START OF ..." and "*** END OF ..."
   marker lines (both markers excluded).
3. Clean: collapse every newline / run of whitespace to one space, strip the
   ends, normalise to Unicode NFC. Case and punctuation are kept.
4. Write data/alice_clean.txt, data/alice_info.md (human-readable, includes
   the full character set) and data/alice_meta.json (the same facts for the
   other scripts to read).

Usage:
    python prepare_alice.py              # download if needed, then clean
    python prepare_alice.py --redownload # force a fresh download
"""

import argparse
import json
import re
import sys
import unicodedata
import urllib.error
import urllib.request
from collections import Counter
from datetime import datetime, timezone

import config
from src.inputs_io import sha256_bytes, sha256_file
from src.report import md_char, md_table

USER_AGENT = "csc755m-string-matching-benchmark/1.0 (academic research script)"


def download(url, dest):
    """Fetch url and save the exact bytes to dest."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = response.read()
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return data


def extract_body(raw_text):
    """Return the lines strictly between the Gutenberg START and END markers."""
    # Split only on real line breaks (str.splitlines would also split on rarer
    # separator characters and silently change the character set).
    lines = raw_text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    start = next(
        (i for i, line in enumerate(lines) if line.startswith(config.GUTENBERG_START_MARKER)), None
    )
    if start is None:
        raise ValueError("START marker line not found in the raw file")
    end = next(
        (
            i
            for i, line in enumerate(lines)
            if i > start and line.startswith(config.GUTENBERG_END_MARKER)
        ),
        None,
    )
    if end is None:
        raise ValueError("END marker line not found in the raw file")
    return "\n".join(lines[start + 1 : end])


def clean_text(body):
    """Collapse whitespace to single spaces, strip the ends, normalise to NFC."""
    collapsed = re.sub(r"\s+", " ", body).strip()
    return unicodedata.normalize("NFC", collapsed)


def write_info(meta, sigma_counts):
    """Write data/alice_info.md."""
    rows = []
    for ch, count in sorted(sigma_counts.items(), key=lambda kv: ord(kv[0])):
        try:
            name = unicodedata.name(ch)
        except ValueError:
            name = "(no name)"
        rows.append([md_char(ch), f"U+{ord(ch):04X}", name, f"{count:,}"])

    lines = [
        "# Alice's Adventures in Wonderland: source text information",
        "",
        "Generated by `prepare_alice.py`.",
        "",
        md_table(
            ["Item", "Value"],
            [
                ["Source", f"Project Gutenberg eBook #11, <{meta['url']}>"],
                ["Download date (UTC)", meta["download_date_utc"]],
                ["Raw file", "`data/alice_raw.txt`"],
                ["Raw character count", f"{meta['raw_char_count']:,}"],
                ["Raw byte count", f"{meta['raw_byte_count']:,}"],
                ["Raw SHA-256", f"`{meta['raw_sha256']}`"],
                ["Clean file", "`data/alice_clean.txt`"],
                ["Clean character count", f"{meta['clean_char_count']:,}"],
                ["Clean byte count (UTF-8)", f"{meta['clean_byte_count']:,}"],
                ["Clean SHA-256", f"`{meta['clean_sha256']}`"],
                ["Alphabet size \\|Σ\\|", f"**{meta['sigma_size']}**"],
            ],
        ),
        "## Cleaning rules",
        "",
        f"1. Keep only the text between the line starting with `{config.GUTENBERG_START_MARKER}` "
        f"and the line starting with `{config.GUTENBERG_END_MARKER}` (both marker lines excluded).",
        "2. Keep upper and lower case and punctuation.",
        "3. Replace every newline and every run of whitespace with a single space; strip both ends.",
        "4. Normalise to Unicode NFC.",
        "",
        f"## Character set Σ (|Σ| = {meta['sigma_size']})",
        "",
        "Sorted by code point. The space is shown as `␠ (space)`.",
        "",
        md_table(["Character", "Code point", "Unicode name", "Count"], rows, ["l", "l", "l", "r"]),
    ]
    config.ALICE_INFO_MD.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--redownload", action="store_true", help="download even if data/alice_raw.txt exists")
    args = parser.parse_args()

    config.DATA_DIR.mkdir(parents=True, exist_ok=True)
    previous_meta = {}
    if config.ALICE_META_JSON.exists():
        previous_meta = json.loads(config.ALICE_META_JSON.read_text(encoding="utf-8"))

    if args.redownload or not config.ALICE_RAW.exists():
        print(f"Downloading {config.ALICE_URL} ...")
        try:
            raw_bytes = download(config.ALICE_URL, config.ALICE_RAW)
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            print(
                f"\nDOWNLOAD FAILED: {exc}\n"
                f"Please download {config.ALICE_URL} yourself, save it as\n"
                f"  {config.ALICE_RAW}\n"
                "and run this script again.",
                file=sys.stderr,
            )
            return 1
        download_date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    else:
        raw_bytes = config.ALICE_RAW.read_bytes()
        same_file = previous_meta.get("raw_sha256") == sha256_bytes(raw_bytes)
        if same_file and previous_meta.get("download_date_utc"):
            download_date = previous_meta["download_date_utc"]
        else:
            mtime = datetime.fromtimestamp(config.ALICE_RAW.stat().st_mtime, timezone.utc)
            download_date = f"unknown (file placed manually; modified {mtime:%Y-%m-%d %H:%M:%S} UTC)"
        print(f"Using existing {config.ALICE_RAW.name} (pass --redownload to fetch again)")

    raw_text = raw_bytes.decode("utf-8-sig")  # utf-8-sig drops a leading BOM if present
    clean = clean_text(extract_body(raw_text))
    config.ALICE_CLEAN.write_text(clean, encoding="utf-8", newline="")

    sigma_counts = Counter(clean)
    meta = {
        "url": config.ALICE_URL,
        "download_date_utc": download_date,
        "raw_char_count": len(raw_text),
        "raw_byte_count": len(raw_bytes),
        "raw_sha256": sha256_bytes(raw_bytes),
        "clean_char_count": len(clean),
        "clean_byte_count": len(clean.encode("utf-8")),
        "clean_sha256": sha256_file(config.ALICE_CLEAN),
        "sigma_size": len(sigma_counts),
        "sigma": "".join(sorted(sigma_counts, key=ord)),
    }
    config.ALICE_META_JSON.write_text(
        json.dumps(meta, indent=2, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n"
    )
    write_info(meta, sigma_counts)

    print(f"Raw:   {meta['raw_char_count']:,} chars  sha256 {meta['raw_sha256']}")
    print(f"Clean: {meta['clean_char_count']:,} chars  sha256 {meta['clean_sha256']}")
    print(f"|Sigma| = {meta['sigma_size']}")
    print(f"Wrote {config.ALICE_CLEAN.relative_to(config.ROOT)}, "
          f"{config.ALICE_INFO_MD.relative_to(config.ROOT)}, {config.ALICE_META_JSON.relative_to(config.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
